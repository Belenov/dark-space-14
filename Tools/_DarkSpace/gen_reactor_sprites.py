def console_screen(d, mode, t, n):
    im = new()
    if d != 0:
        return im
    ph = 2 * math.pi * t / n
    if mode == "off":
        for y in range(7, 16):
            for x in range(8, 24):
                put(im, x, y, (10, 16, 12, 255))
        put(im, 9, 8, (60, 80, 64)); put(im, 10, 8, (44, 60, 48))
        return im
    alarm = mode == "alarm"
    on = (t % 2 == 0)
    col = (255, 70, 50) if alarm else (110, 255, 140)
    dim = mul(col, 0.35)
    for y in range(7, 16):
        for x in range(8, 24):
            put(im, x, y, (40, 8, 6, 255) if alarm and on else (6, 22, 12, 255) if not alarm else (14, 6, 6, 255))
    if alarm:
        if on:
            for k in range(10, 22):  # flashing exclamation band
                put(im, k, 7, col)
                put(im, k, 15, col)
            for y in range(8, 13): rect(im, 15, y, 16, y, col)
            rect(im, 15, 14, 16, 14, col)
        else:
            for y in (9, 11, 13): rect(im, 9, y, 22, y, dim)
    else:
        for k in range(5):  # bars: zone power / temperature / rods
            h = int(2 + 5 * (0.5 + 0.5 * math.sin(ph + k * 1.3)))
            rect(im, 9 + k * 3, 15 - h, 10 + k * 3, 14, col if k % 2 == 0 else (230, 200, 60))
        for x in range(9, 23):  # scrolling trace
            y = 8 + int(1.4 + 1.3 * math.sin(x * 0.7 - ph * 2))
            put(im, x, y, dim if x % 2 else col)
    lamps = [(90, 230, 110), (90, 230, 110), (230, 190, 50), (60, 70, 60), (60, 70, 60)]
    if alarm:
        lamps = [(230, 50, 40) if on else (90, 30, 26)] * 3 + [(230, 190, 50), (60, 70, 60)]
    for k, lc in enumerate(lamps):
        rect(im, 8 + k * 3, 17, 9 + k * 3, 17, lc)
    return im


# ---------------------------------------------------------------- writing
def strip(frames):
    im = new(S * len(frames), S)
    for i, f in enumerate(frames):
        im.paste(f, (S * i, 0))
    return im


def write_rsi(path, states):
    """states: list of (name, frames|list-of-dirs, delay, dirs)"""
    os.makedirs(path, exist_ok=True)
    meta = {"version": 1, "license": LICENSE, "copyright": COPY, "size": {"x": S, "y": S}, "states": []}
    for name, frames, delay, dirs in states:
        strip(frames).save(os.path.join(path, name + ".png"))
        e = {"name": name}
        if dirs > 1:
            e["directions"] = dirs
        if delay:
            per = len(frames) // dirs
            e["delays"] = [[delay] * per for _ in range(dirs)]
        meta["states"].append(e)
    with open(os.path.join(path, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2); f.write("\n")


def main():
    preview_dir = None
    if "--preview" in sys.argv:
        preview_dir = sys.argv[sys.argv.index("--preview") + 1]
    registry = {}

    # channel tiles
    ch, ov = [], []
    combos = [("empty", "normal", 1), ("empty", "damaged", 4),
              ("fuel", "normal", 4), ("fuel", "hot", 4), ("fuel", "damaged", 4),
              ("rod", "normal", 1), ("rod", "hot", 4), ("rod", "damaged", 4),
              ("graphite", "normal", 1), ("graphite", "hot", 4), ("graphite", "damaged", 4)]
    for kind, cond, n in combos:
        name = kind if cond == "normal" else f"{kind}-{cond}"
        frames = [comp(*render(kind, cond, t, n)) for t in range(n)]
        ch.append((name, frames, 0.25 if n > 1 else 0, 1))
        registry[name] = frames
    # melted channel
    mf = [render_melted(t, 4) for t in range(4)]
    ch.append(("melted", mf, 0.2, 1)); registry["melted"] = mf
    # unshaded overlays for code that wants a separate glow layer
    ov.append(("glow-fuel", [render("fuel", "normal", t, 4)[1] for t in range(4)], 0.25, 1))
    ov.append(("glow-hot", [render("rod", "hot", t, 4)[1] for t in range(4)], 0.25, 1))
    ov.append(("glow-damaged", [render("rod", "damaged", t, 4)[1] for t in range(4)], 0.25, 1))
    # bare hall floor variants live next to the channel tiles
    fl = floor_states()
    ch += [(k, v, 0, 1) for k, v in fl.items()]
    write_rsi(f"{OUT}/reactor_channel.rsi", ch + ov)

    # corium and meltdown
    co = [
        ("corium", [blob(t, 4, 12.5, seed=1) for t in range(4)], 0.25, 1),
        ("corium-crust", [blob(t, 2, 12.5, seed=1, crust=True) for t in range(2)], 0.6, 1),
        ("meltdown", [blob(t, 4, 0, seed=3, full=True) for t in range(4)], 0.2, 1),
    ]
    for name, fr, _, _ in co: registry[name] = fr
    write_rsi(f"{OUT}/reactor_corium.rsi", co)

    # SUZ console: body has 4 directions (S, N, E, W); screen overlays are unshaded
    body = [console_dir(d) for d in range(4)]
    scr = {m: [console_screen(d, m, t, 4) for d in range(4) for t in range(4)] for m in ("on", "alarm")}
    scr["off"] = [console_screen(d, "off", 0, 1) for d in range(4)]
    write_rsi(f"{OUT}/suz_console.rsi", [
        ("suz", body, 0, 4),
        ("screen-on", scr["on"], 0.3, 4),
        ("screen-alarm", scr["alarm"], 0.35, 4),
        ("screen-off", scr["off"], 0, 4),
    ])
    registry["console_body"] = body[:1]
    registry["console_on"] = [comp(body[0], scr["on"][t]) for t in range(4)]
    registry["console_alarm"] = [comp(body[0], scr["alarm"][t]) for t in range(4)]
    registry["console_back"] = [body[1]]; registry["console_e"] = [body[2]]; registry["console_w"] = [body[3]]
    print("wrote RSIs to", OUT)

    if preview_dir:
        make_preview(registry, preview_dir)


def make_preview(reg, outdir):
    os.makedirs(outdir, exist_ok=True)
    bg = (14, 15, 16, 255)
    layout = ["GFGFG", "FRFRF", "GFGFG", "FRFRF", "GFGFG"]
    kmap = {"G": "graphite", "F": "fuel", "R": "rod", ".": "empty"}

    def grid(fn, t):
        im = Image.new("RGBA", (S * 5, S * 5), bg)
        for r, row in enumerate(layout):
            for c, ch in enumerate(row):
                k = kmap[ch]
                cond = fn(r, c, k)
                name = k if cond == "normal" else f"{k}-{cond}"
                if name not in reg: name = k
                fr = reg[name]
                if cond == "melted": fr = reg["melted"]
                im.alpha_composite(fr[t % len(fr)], (c * S, r * S))
        return im

    def hotmix(r, c, k):
        d = math.hypot(r - 2, c - 2)
        if d < 1.2: return "melted"
        if d < 2.3: return "hot"
        if (r * 3 + c) % 7 == 0: return "damaged"
        return "normal"

    scale = 5
    scenes = [lambda r, c, k: "normal", lambda r, c, k: "hot", lambda r, c, k: "damaged", hotmix]
    labels = ["norm", "hot", "dmg", "meltdown"]
    frames = []
    for t in range(4):
        sheet = Image.new("RGBA", (S * 5 * 4 + 30 * 3 + 40, S * 5 + 40), bg)
        x = 20
        for sc in scenes:
            g = grid(sc, t)
            sheet.alpha_composite(g, (x, 20)); x += S * 5 + 30
        frames.append(sheet)
    a = frames[0].resize((frames[0].width * 2, frames[0].height * 2), Image.NEAREST)
    # state catalogue
    names = [n for n in reg]
    cols = 8
    rows = (len(names) + cols - 1) // cols
    cat = Image.new("RGBA", (cols * (S + 6) + 6, rows * (S + 6) + 6), bg)
    for i, n in enumerate(names):
        cat.alpha_composite(reg[n][0], (6 + (i % cols) * (S + 6), 6 + (i // cols) * (S + 6)))
    cat = cat.resize((cat.width * 4, cat.height * 4), Image.NEAREST)
    a.save(os.path.join(outdir, "reactor_grids.png"))
    cat.save(os.path.join(outdir, "reactor_catalogue.png"))
    big = [f.resize((f.width * 2, f.height * 2), Image.NEAREST).convert("P", palette=Image.ADAPTIVE) for f in frames]
    big[0].save(os.path.join(outdir, "reactor_grids.gif"), save_all=True, append_images=big[1:], duration=250, loop=0)
    # console + corium row
    row = Image.new("RGBA", (S * 10 + 20 * 2 + 6, S * 2 + 20), bg)
    for i, n in enumerate(["console_body", "console_on", "console_alarm", "console_back", "console_e", "console_w"]):
        row.alpha_composite(reg[n][0 if n != "console_alarm" else 0], (10 + i * (S + 6), 10))
        if n in ("console_on", "console_alarm"): row.alpha_composite(reg[n][1], (10 + i * (S + 6), 10 + S + 4))
    for i, n in enumerate(["corium", "corium-crust", "meltdown"]):
        row.alpha_composite(reg[n][1 % len(reg[n])], (10 + (6 + i) * (S + 6) + 10, 10))
    row.resize((row.width * 5, row.height * 5), Image.NEAREST).save(os.path.join(outdir, "reactor_console_corium.png"))
    print("preview in", outdir)


if __name__ == "__main__":
    main()
