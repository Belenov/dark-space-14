#!/usr/bin/env python3
"""Generates the IR-7 "Zarya" reactor sprites (RSI) into Resources/Textures/_DarkSpace/Structures/Power/.

Run from the repo root:  python3 Tools/_DarkSpace/gen_reactor_sprites.py [--preview DIR]
Needs Pillow. Output is deterministic (seeded), so regenerating produces identical files.
"""
import json, math, os, random, sys
from PIL import Image

S = 32
OUT = "Resources/Textures/_DarkSpace/Structures/Power"
LICENSE = "CC-BY-SA-3.0"
COPY = "Created for Dark Space by Claude, generated by Tools/_DarkSpace/gen_reactor_sprites.py"


def new(w=S, h=S):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def rgba(c, a=255):
    return (c[0], c[1], c[2], c[3] if len(c) > 3 else a)


def put(im, x, y, c):
    if 0 <= x < im.width and 0 <= y < im.height:
        im.putpixel((x, y), rgba(c))


def mix(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def mul(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c[:3])


def rect(im, x0, y0, x1, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            put(im, x, y, c)


def hsh(*a):
    return random.Random(hash(a) & 0xFFFFFFFF if False else sum((i + 7) * 31 ** k * (v + 13) for k, (i, v) in enumerate(enumerate(a)))).random()


def px_iter(r_max=None, cx=16.0, cy=16.0):
    for y in range(S):
        for x in range(S):
            dx, dy = x + 0.5 - cx, y + 0.5 - cy
            r = math.hypot(dx, dy)
            if r_max is None or r <= r_max:
                yield x, y, dx, dy, r


# ---------------------------------------------------------------- reactor channel tile
STEEL = (46, 52, 49)


def plate():
    im = new()
    for y in range(S):
        for x in range(S):
            n = (hsh(x, y, 1) - 0.5) * 7
            c = tuple(int(v + n) for v in STEEL)
            if x == 0 or y == 0:
                c = (82, 90, 84)
            elif x == 1 or y == 1:
                c = (62, 69, 64)
            elif x == S - 1 or y == S - 1:
                c = (20, 23, 22)
            elif x == S - 2 or y == S - 2:
                c = (30, 34, 32)
            put(im, x, y, c)
    for (rx, ry) in ((3, 3), (27, 3), (3, 27), (27, 27)):
        rect(im, rx, ry, rx + 1, ry + 1, (88, 94, 88))
        put(im, rx + 1, ry + 1, (28, 30, 28))
    # painted radiation-yellow corner marks
    for i in range(4):
        put(im, 5 + i, 2, (150, 125, 30)); put(im, 26 - i, 2, (150, 125, 30))
    return im


def recess(im, dark=True):
    for x, y, dx, dy, r in px_iter(13.5):
        if r <= 11.0:
            c = (12, 13, 14) if dark else (20, 22, 22)
        elif r <= 12.2:  # inner rim, lit from top-left
            t = -(dx + dy) / (2 * r)
            c = mix((36, 40, 38), (108, 116, 108), (t + 1) / 2)
        elif r <= 13.5:  # outer bevel
            t = (dx + dy) / (2 * r)
            c = mix((24, 27, 26), (74, 82, 76), (t + 1) / 2)
        put(im, x, y, c)


def shade(c, dx, dy, k=0.5):
    return mul(c, 1 - (dx + dy) / 21.0 * k)


CAP_R = 10.4


def cap_empty(im):
    for x, y, dx, dy, r in px_iter(CAP_R):
        c = mix((16, 17, 19), (2, 2, 3), 1 - r / CAP_R)
        put(im, x, y, c)
    for i in range(-8, 9, 4):  # grating
        for k in range(-9, 10):
            for (ax, ay) in ((16 + i, 16 + k), (16 + k, 16 + i)):
                if math.hypot(ax - 15.5, ay - 15.5) <= CAP_R - 0.6:
                    put(im, ax, ay, (58, 63, 60) if (k + i) % 2 else (40, 44, 42))


def cap_fuel(im):
    for x, y, dx, dy, r in px_iter(CAP_R):
        c = shade((56, 84, 52), dx, dy)
        if 8.6 <= r <= 9.4:
            c = (28, 44, 28)
        put(im, x, y, c)
    for k in range(6):  # bolts
        a = k * math.pi / 3 + 0.5
        bx, by = int(16 + 7.4 * math.cos(a)) - 1, int(16 + 7.4 * math.sin(a)) - 1
        rect(im, bx, by, bx + 1, by + 1, (110, 118, 108)); put(im, bx + 1, by + 1, (40, 44, 40))
    for x, y, dx, dy, r in px_iter(5.2):
        if r < 4.6:
            put(im, x, y, (20, 30, 20))
    for x, y, dx, dy, r in px_iter(4.2):  # radiation trefoil
        if 1.5 <= r <= 4.2 and (math.degrees(math.atan2(dy, dx)) + 90) % 120 < 60:
            put(im, x, y, (232, 200, 40))
    rect(im, 15, 15, 16, 16, (232, 200, 40))


def cap_rod(im):
    for x, y, dx, dy, r in px_iter(CAP_R):
        c = shade((50, 68, 100), dx, dy)
        if 8.6 <= r <= 9.4:
            c = (26, 34, 54)
        put(im, x, y, c)
    for (ox, oy) in ((0, -1), (1, 0), (0, 1), (-1, 0)):  # amber graduation ticks
        for k in range(6, 9):
            put(im, int(15.5 + ox * k + (0 if ox == 0 else 0)), int(15.5 + oy * k), (214, 152, 40))
            if ox == 0: put(im, 16, int(15.5 + oy * k), (214, 152, 40))
            else: put(im, int(15.5 + ox * k), 16, (214, 152, 40))
    for x, y, dx, dy, r in px_iter(5.2):  # the rod itself
        if r < 5.0:
            put(im, x, y, mix((90, 104, 130), (22, 26, 40), min(1, r / 5) ** 0.7 * 0.0 + (dx + dy + 7) / 14))
    for x, y, dx, dy, r in px_iter(3.0):
        put(im, x, y, mix((150, 172, 210), (34, 42, 66), (dx + dy + 4) / 8))
    put(im, 14, 14, (200, 220, 245))


def cap_graphite(im):
    for x, y, dx, dy, r in px_iter(CAP_R):
        c = shade((38, 38, 43), dx, dy, 0.6)
        if (int(x) % 5 == 0) or (int(y) % 5 == 0):
            c = mul(c, 1.5)
        c = mul(c, 0.9 + hsh(x, y, 5) * 0.2)
        if 9.0 <= r:
            c = (22, 22, 26)
        put(im, x, y, c)
    for (bx, by) in ((11, 11), (19, 19)):  # a couple of glossy blocks
        put(im, bx, by, (96, 96, 108)); put(im, bx + 1, by, (76, 76, 88))


CAPS = {"empty": cap_empty, "fuel": cap_fuel, "rod": cap_rod, "graphite": cap_graphite}


def cracks(seed, n=3):
    rnd = random.Random(seed)
    pts = []
    for _ in range(n):
        a = rnd.uniform(0, 2 * math.pi)
        x, y = 16 + 11 * math.cos(a), 16 + 11 * math.sin(a)
        d = a + math.pi + rnd.uniform(-0.5, 0.5)
        for _ in range(rnd.randint(8, 13)):
            pts.append((int(x), int(y)))
            d += rnd.uniform(-0.6, 0.6)
            x += math.cos(d); y += math.sin(d)
    return pts


def damage_base(im, kind, seed):
    rnd = random.Random(seed)
    for x, y, dx, dy, r in px_iter(CAP_R):  # soot
        v = hsh(x // 2, y // 2, seed)
        if v > 0.55 and kind != "empty":
            put(im, x, y, mul(im.getpixel((x, y)), 0.5))
    a0 = rnd.uniform(0, 2 * math.pi)
    for x, y, dx, dy, r in px_iter(CAP_R + 1):  # chunk missing from the cap edge
        da = (math.atan2(dy, dx) - a0 + math.pi) % (2 * math.pi) - math.pi
        if r > 6.5 - 2 * math.cos(da * 3) and abs(da) < 0.55:
            put(im, x, y, (5, 5, 6))
    for (x, y) in cracks(seed):
        put(im, x, y, (6, 6, 7))
    for (rx, ry) in ((3, 27), (27, 3)):  # a bent rivet
        rect(im, rx, ry, rx + 1, ry + 1, (20, 20, 20))
    for i in range(6):  # scorch on plate
        put(im, 2 + i, 29 - i // 2, (20, 20, 18))


def render(kind, cond, t=0, n=1):
    """Returns (base, glow); glow is meant to be drawn unshaded on top of base."""
    seed = {"empty": 1, "fuel": 2, "rod": 3, "graphite": 4}[kind] * 11
    base = plate(); recess(base); CAPS[kind](base)
    if cond == "damaged":
        damage_base(base, kind, seed)
    glow = new()
    ph = 2 * math.pi * t / max(n, 1)
    if kind == "fuel":  # Cherenkov glow of a live fuel channel
        for x, y, dx, dy, r in px_iter(9.6):
            a = (0.26 + 0.20 * math.sin(ph)) * (1 - (r / 10) ** 2) + 0.10
            put(glow, x, y, (90, 220, 255, int(255 * min(a, 0.9))))
        for x, y, dx, dy, r in px_iter(2.2):
            put(glow, x, y, (200, 250, 255, int(255 * (0.55 + 0.3 * math.sin(ph)))))
    if cond == "hot":
        p = 0.6 + 0.4 * math.sin(ph + 1.0)
        for x, y, dx, dy, r in px_iter(16.5):
            if r <= 9.6:
                a = 0.16 + 0.12 * p
                col = (255, 96, 24)
            elif r <= 12.6:
                a = 0.55 * p + 0.2
                col = (255, 120, 30)
            elif r <= 16.5:
                a = 0.20 * p * (1 - (r - 12.6) / 3.9)
                col = (255, 90, 20)
            else:
                continue
            put(glow, x, y, col + (int(255 * a),))
        if kind == "fuel":
            for x, y, dx, dy, r in px_iter(3.0):
                put(glow, x, y, (255, 235, 170, int(255 * (0.6 + 0.3 * p))))
    if cond == "damaged":
        pts = cracks({"empty": 11, "fuel": 22, "rod": 33, "graphite": 44}[kind])
        for i, (x, y) in enumerate(pts):
            if i % 3 == 0 and hsh(i, t, 9) > 0.45:
                put(glow, x, y, (255, 150, 40, 235) if hsh(i, t, 4) > 0.4 else (255, 215, 90, 255))
        rr = random.Random(seed + t * 17)  # sparks
        if t % 2 == 0:
            sx, sy = rr.randint(6, 25), rr.randint(6, 25)
            put(glow, sx, sy, (255, 240, 160, 255))
            put(glow, sx + 1, sy, (255, 190, 70, 160))
    return base, glow


def comp(base, glow):
    return Image.alpha_composite(base, glow)


# ---------------------------------------------------------------- corium / meltdown
def blob(t, n, radius, seed=0, full=False, crust=False):
    im = new()
    ph = 2 * math.pi * t / n
    rr = random.Random(seed)
    for x, y, dx, dy, r in px_iter():
        a = math.atan2(dy, dx)
        wob = 1.6 * math.sin(3 * a + 1.1 + seed) + 1.1 * math.sin(5 * a - 0.7 * seed + ph) + 0.7 * math.sin(2 * a + ph)
        edge = (radius + wob) - r if not full else 9.0
        if edge <= 0:
            continue
        sw = math.sin(x * 0.55 + ph + seed) + math.sin(y * 0.5 - ph) + math.sin((x + y) * 0.35 + ph * 1.0)
        heat = min(1.0, edge / 5.0) * 0.55 + (sw + 3) / 6 * 0.45
        if full:
            heat = (sw + 3) / 6
        if crust:
            heat = 0.0 if hsh(x // 3, y // 3, seed) > 0.28 else 0.55 + 0.2 * math.sin(ph + x)
            c = mix((22, 20, 21), (200, 60, 16), heat) if heat else mul((36, 32, 33), 0.8 + hsh(x, y, 3) * 0.5)
        elif heat < 0.30:
            c = mix((36, 16, 12), (170, 38, 12), heat / 0.30)
        elif heat < 0.62:
            c = mix((170, 38, 12), (255, 122, 22), (heat - 0.30) / 0.32)
        else:
            c = mix((255, 122, 22), (255, 236, 150), (heat - 0.62) / 0.38)
        put(im, x, y, c)
    if not crust:
        for i in range(4):  # bubbles
            bx, by = rr.randint(8, 23), rr.randint(8, 23)
            if hsh(i, t, seed) > 0.4 and im.getpixel((bx, by))[3]:
                put(im, bx, by, (255, 250, 200)); put(im, bx + 1, by, (255, 200, 90))
    return im


def render_melted(t, n):
    base = plate(); recess(base, dark=True)
    for x, y, dx, dy, r in px_iter(16):  # scorched plate
        if base.getpixel((x, y))[3] and 12.2 < r < 16:
            put(base, x, y, mul(base.getpixel((x, y)), 0.45))
    pool = blob(t, n, 10.6, seed=2)
    return comp(base, pool)


# ---------------------------------------------------------------- floor
def floor_states():
    st = {}
    st["plate"] = [plate()]
    worn = plate()
    for x, y, dx, dy, r in px_iter():
        v = hsh(x, y, 77)
        if v > 0.93: put(worn, x, y, (26, 28, 27))
        elif v < 0.03: put(worn, x, y, (96, 78, 52))
    st["plate-worn"] = [worn]
    hz = new()
    for y in range(S):
        for x in range(S):
            put(hz, x, y, (200, 165, 25) if ((x + y) // 4) % 2 == 0 else (24, 24, 22))
    for i in range(S):
        for k in (0, 1, S - 1, S - 2):
            put(hz, i, k, (18, 18, 18)); put(hz, k, i, (18, 18, 18))
    st["hazard"] = [hz]
    return st


