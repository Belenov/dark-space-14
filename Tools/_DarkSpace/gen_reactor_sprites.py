def shell_base():
    im = new(SH, SH)
    for y in range(SH):
        for x in range(SH):
            dx, dy, d_out, d_in, hole = shell_metrics(x, y)
            if d_out < 0 or hole:
                continue
            n = (hsh(x, y, 21) - 0.5) * 8
            light = -((x - SH / 2) + (y - SH / 2)) / SH * 10
